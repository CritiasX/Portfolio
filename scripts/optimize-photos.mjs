import { mkdir, stat, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import sharp from 'sharp'

const root = fileURLToPath(new URL('../', import.meta.url))
const output = path.join(root, 'public/photos/optimized')
const sources = {
  graduation: 'james-graduation.jpg',
  downtime: 'james-downtime.jpg',
  moment: 'james-moment.jpg',
}
const widths = [480, 960, 1440]
const assets = {}
let sourceBytes = 0
let defaultBytes = 0
await mkdir(output, { recursive: true })

for (const [name, filename] of Object.entries(sources)) {
  const input = path.join(root, 'public/photos', filename)
  sourceBytes += (await stat(input)).size
  const variants = []
  for (const width of widths) {
    const filename = `james-${name}-${width}.webp`
    const info = await sharp(input).rotate().resize({ width, withoutEnlargement: true })
      .webp({ quality: 80, effort: 5 }).toFile(path.join(output, filename))
    variants.push({ src: `/photos/optimized/${filename}`, width: info.width, height: info.height, bytes: info.size })
  }
  const fallback = variants[1]
  assets[name] = {
    src: fallback.src,
    srcSet: variants.map(({ src, width }) => `${src} ${width}w`).join(', '),
    width: fallback.width,
    height: fallback.height,
  }
  defaultBytes += fallback.bytes
  console.log(`${name}: ${variants.map(({ width, bytes }) => `${width}px ${(bytes / 1024).toFixed(1)} KiB`).join(' / ')}`)
}

await writeFile(path.join(root, 'src/photoAssets.js'),
  `// Generated by pnpm images:optimize. Keep the original photos for future updates.\nexport const photoAssets = ${JSON.stringify(assets, null, 2)}\n`)
console.log(`Default photo payload: ${(sourceBytes / 1024).toFixed(1)} → ${(defaultBytes / 1024).toFixed(1)} KiB (${Math.round((1 - defaultBytes / sourceBytes) * 100)}% smaller).`)
